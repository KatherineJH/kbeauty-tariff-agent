-- Rule segments joined to their sourced action, with the boundary-uncertain windows of date-precision boundaries.
select
    s.segment_id,
    s.action_id,
    s.duty_family,
    a.legal_basis,
    a.legal_basis_key,
    s.origin_country,
    s.hts_scope,
    s.hts_scope_kind,
    s.hts_list_id,
    s.transport_scope,
    s.effect_kind,
    s.value_component,
    s.starts_at,
    s.starts_at_source,
    s.starts_precision,
    s.starts_on,
    case when s.starts_precision = 'date' then s.starts_at + interval 1 day end as start_uncertain_until,
    s.ends_at,
    s.ends_at_source,
    s.ends_precision,
    s.ends_on,
    case when s.ends_precision = 'date' then s.ends_at + interval 1 day end      as end_uncertain_until,
    s.rate_kind,
    s.rate_pct,
    a.stacking_rule,
    a.evidence_status,
    s.segment_resolution_status                                       as resolution_status,
    s.segment_resolution_note,
    a.resolution_status                                               as action_resolution_status,
    a.open_issues,
    s.segment_note
from {{ ref('stg_rule_segments') }} s
join {{ ref('stg_regulatory_actions') }} a using (action_id)
