-- Sourced regulatory actions with explicit types. The source time text is kept next to each parsed TIMESTAMPTZ.
select
    action_id,
    instrument,
    legal_basis,
    trim(split_part(split_part(legal_basis, ' (', 1), ',', 1))      as legal_basis_key,
    cast(nullif(trim(signed_at), '') as date)                        as signed_on,
    cast(nullif(trim(published_at), '') as date)                     as published_on,
    nullif(trim(effective_at), '')                                    as effective_at_source,
    {{ parse_ts('effective_at') }}                                    as effective_at,
    {{ ts_precision('effective_at') }}                                as effective_precision,
    nullif(trim(ends_at), '')                                         as ends_at_source,
    {{ parse_ts('ends_at') }}                                         as ends_at,
    {{ ts_precision('ends_at') }}                                     as ends_precision,
    ends_rule,
    applicability_rule,
    scope,
    rate_or_effect,
    rate_kind,
    cast(nullif(trim(rate_pct), '') as decimal(6, 3))                 as rate_pct,
    stacking_rule,
    supersedes,
    superseded_by,
    amends,
    unaffected_actions,
    source_quote_ref,
    archive_evidence,
    cosmetics_3303_3307,
    evidence_status,
    resolution_status,
    nullif(trim(open_issues), '')                                     as open_issues
from {{ ref('regulatory_actions') }}
